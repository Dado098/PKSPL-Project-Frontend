export interface ChatMessage {
  id: string;
  senderId: string; // 'superadmin', user id, or 'peneliti-me'
  senderName: string;
  text: string;
  timestamp: string;
  isOutgoing: boolean;
  status?: 'sent' | 'delivered' | 'read';
  isEdited?: boolean;
  isDeleted?: boolean;
  error?: boolean;
  attachment?: {
    name: string;
    type: 'file' | 'image' | 'shp';
    size: string;
    url?: string;
  };
}

